export interface FlatLab extends Lab {
  mod: LabModule;
}

/** 모듈 순서대로 펼친 전체 실습 목록 — 이전/다음 이동에 쓴다. */
export const FLAT_LABS: FlatLab[] = MODULES.flatMap((m) =>
  m.labs.map((l) => ({ ...l, mod: m }))
);

export const findLab = (id: string) => FLAT_LABS.find((l) => l.id === id);

export const findModule = (num: number) => MODULES.find((m) => m.num === num);

export const labIndex = (id: string) => FLAT_LABS.findIndex((l) => l.id === id);

export const moduleZip = (num: number) => `${ASSETS}/Module${num}_실습파일.zip`;

export const moduleHasFiles = (m: LabModule) => m.labs.some((l) => l.files.length > 0);

/** 실습에 실제로 등장하는 도구 — 라이브러리 필터가 이 목록에서 만들어진다 (많이 쓰이는 순) */
export const ALL_TOOLS: string[] = [
  ...FLAT_LABS.reduce((count, l) => {
    for (const t of l.tools) count.set(t, (count.get(t) ?? 0) + 1);
    return count;
  }, new Map<string, number>()),
]
  .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0], "ko"))
  .map(([tool]) => tool);

/** 랜딩 통계 — 하드코딩하지 않고 데이터에서 계산한다. */
export const LAB_STATS = {
  modules: MODULES.length,
  labs: FLAT_LABS.length,
  files: new Set(FLAT_LABS.flatMap((l) => l.files.map((x) => x.path))).size,
  prompts: FLAT_LABS.reduce((n, l) => n + l.prompts.length, 0),
};
